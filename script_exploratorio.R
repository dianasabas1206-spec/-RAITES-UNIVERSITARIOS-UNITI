library(DBI)
library(RSQLite)
library(dplyr)
library(DT)
con <- dbConnect(RSQLite::SQLite(), "raites_universitarios.db")
dbListTables(con)
viaje <- dbReadTable(con, "viaje")
datatable(viaje)
consulta_origen <- dbGetQuery(con, "SELECT origen, COUNT(id_viaje) AS total_viajes FROM viaje GROUP BY origen")
print(consulta_origen)
consulta_completa <- dbGetQuery(con, "SELECT usuario.nombre, vehiculo.tipo_vehiculo, viaje.origen, viaje.horario FROM viaje INNER JOIN usuario ON viaje.id_usuario = usuario.id_usuario INNER JOIN vehiculo ON viaje.id_vehiculo = vehiculo.id_vehiculo")
datatable(consulta_completa)
dbDisconnect(con)
